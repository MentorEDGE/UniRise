      {tab === "harvest" && <Card><CardHeader><CardTitle>Harvest status</CardTitle><CardDescription>Last run pulls works from ORCID and OpenAlex.</CardDescription></CardHeader>
        <CardContent><dl className="grid gap-4 sm:grid-cols-3 text-sm">{[["Last run", "Today, 02:00"], ["Researchers with ORCID", "9 of 12"], ["New suggestions", "6"]].map(([k, v]) => <div key={k}><dt className="text-xs uppercase tracking-wider text-muted-foreground">{k}</dt><dd className="text-lg font-semibold">{v}</dd></div>)}</dl></CardContent></Card>}
