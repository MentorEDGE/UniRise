function Keys() {
  const { toast } = useToast();
  const [key, setKey] = useState<string | null>(null);
  const create = () => {
    const bytes = crypto.getRandomValues(new Uint8Array(32));
    setKey("rms_" + Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join(""));
  };
  return (
    <Card><CardHeader><CardTitle>API keys</CardTitle><CardDescription>For service integrations. A key is shown once, so copy it now. Real keys are generated by the server.</CardDescription></CardHeader>
      <CardContent className="space-y-4">
        <Button onClick={create}><KeyRound /> Create key (demo)</Button>
        {key && (
          <div role="status" className="space-y-2 rounded-xl border border-warning/40 bg-warning/10 p-4">
            <p className="text-sm font-semibold">Copy this key now. You won't see it again.</p>
            <code className="block break-all rounded-lg bg-background p-3 text-xs">{key}</code>
            <Button size="sm" variant="secondary" onClick={async () => { await navigator.clipboard.writeText(key); toast({ tone: "ok", message: "Copied." }); }}><Copy /> Copy</Button>
            <Button size="sm" variant="ghost" onClick={() => setKey(null)}>Done</Button>
          </div>)}
      </CardContent></Card>
  );
}

